// مُرشد — static help content. Sprint 9L(1).
//
// EVERYTHING HERE IS STATIC AND COSTS NOTHING. That is the point: the guide,
// the FAQ and the quick actions answer the majority of questions with no model
// call at all, so the AI budget is spent only on the questions that genuinely
// need live data.
//
// Keyed by the `data-screen-label` each page already renders — the panel reads
// that attribute from the DOM rather than being told where it is, so no page
// component had to change to gain help content (Escalations is the exception:
// it was the one page missing its label).
//
// LANGUAGE: Arabic first, Latin digits throughout (the platform's standing
// rule). Tab and screen names are quoted in English because that is what the
// user sees on screen — translating them in the help text would send someone
// hunting for a button that does not exist.
//
// This file deliberately does NOT live in src/lib: that directory is the
// generator surface and is frozen under a sha256 manifest.

